export type VisualKind =
  | "eye" // глаз / «ты не видишь настоящее»
  | "sun" // Солнце, 8 минут
  | "star" // ближайшая звезда, 4 года
  | "galaxy" // глубокий космос, 13 млрд лет
  | "forest" // тёмный лес
  | "silence" // радиомолчание космоса
  | "hunter" // шорох / охотник в лесу
  | "brain" // всплеск мозга -500 мс
  | "button" // кнопка / действие
  | "commentator" // «ты — комментатор»
  | "cta"; // финальный экран: подписка / сохрани

export type Scene = {
  voiceText: string;
  caption: string;
  /** Крупный текст. *звёздочки* выделяют акцентное слово цветом. */
  title: string;
  eyebrow: string;
  visual: VisualKind;
  /** Большая цифра/факт поверх визуала, напр. «8 мин». */
  stat?: string;
  statLabel?: string;
};

